// Generates the Android app's locales_config.xml from the languages opencode's UI ships, so
// Android 13+ lists the app under Settings > App languages. The WebView passes the chosen
// language to the UI as navigator.languages. Regenerate after bumping opencode:
//   bun build/locales-config.ts
import fs from "node:fs"
import { fileURLToPath } from "node:url"
import {
  DESKTOP_NATIVE_LOCALES,
  DESKTOP_NATIVE_LOCALE_TAGS,
  type DesktopNativeLocale,
} from "../../vendor/opencode-v1/packages/app/src/i18n/desktop-native"

export const LOCALES_CONFIG = fileURLToPath(new URL("../android/app/src/main/res/xml/locales_config.xml", import.meta.url))

// The tag Android shows for an opencode locale. The WebView passes only the language and
// region of the app's locale to navigator.languages (zh-Hant arrives as "zh"), so a locale
// whose script is not its language's usual one (pa-Arab), or that shares its language with
// another locale (zh, zht), is named by language and region instead: pa-PK, zh-CN, zh-TW.
// Other regions in opencode's tags (it-IT, ca-AD) are dropped so the settings list names no
// country, except for "br", whose translation is Brazilian Portuguese.
export function androidTag(code: DesktopNativeLocale): string {
  const tag = new Intl.Locale(DESKTOP_NATIVE_LOCALE_TAGS[code]).maximize()
  const usual = new Intl.Locale(tag.language).maximize()
  const shared = DESKTOP_NATIVE_LOCALES.some(
    (other) => other !== code && new Intl.Locale(DESKTOP_NATIVE_LOCALE_TAGS[other]).language === tag.language,
  )
  return shared || tag.script !== usual.script || code === "br" ? `${tag.language}-${tag.region}` : tag.language
}

export function localesConfigXml(): string {
  const locales = DESKTOP_NATIVE_LOCALES.map((code) => `    <locale android:name="${androidTag(code)}" />\n`).join("")
  return (
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    "<!-- Generated by ui/build/locales-config.ts from opencode's UI languages. Do not edit. -->\n" +
    '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n' +
    locales +
    "</locale-config>\n"
  )
}

if (import.meta.main) {
  fs.writeFileSync(LOCALES_CONFIG, localesConfigXml())
  console.log(`wrote ${LOCALES_CONFIG}`)
}
